/**
 * Стык двух секций.
 *
 * До этого секции просто приставлялись друг к другу: фон менялся мгновенно,
 * прямой горизонтальной линией во всю ширину. Именно эта линия и читается
 * дёшево — страница распадается на плитки, а не течёт.
 *
 * Приём выбирается по фонам, а не по вкусу. На главной их всего два —
 * `#0a0a0a` и `#0d1525`, — и чередуются они не строго:
 *
 * - **Фоны разные** → растворение. Один цвет перетекает в другой на 140
 *   пикселях, границы не остаётся вовсе. Таких стыков двенадцать.
 * - **Фоны одинаковые** → растворять нечего. Без шва два блока сливаются в
 *   один длинный, поэтому ставится волосяная линия с мягким свечением.
 *   Таких стыков два, и оба стоят перед деньгами: «Наш зал» после
 *   «Направлений» и «Стоимость» сразу после формы заявки.
 *
 * Элемент нулевой высоты: полоса висит абсолютно и не двигает вёрстку.
 * Непрозрачна она только в середине, а к краям сходит на нет — текст секций
 * лежит за их внутренними отступами и под неё не попадает.
 */
export default function SectionSeam({ from, to }: { from: string; to: string }) {
  const same = from === to;

  return (
    <div aria-hidden className="relative z-20 h-0 pointer-events-none">
      {same ? (
        <>
          <div className="absolute inset-x-0 -top-px h-px bg-gradient-to-r from-transparent via-blue-400/45 to-transparent" />
          <div
            className="absolute left-1/2 -translate-x-1/2 -top-[60px] h-[120px] w-[760px] max-w-[92vw]"
            style={{
              background:
                "radial-gradient(ellipse at center, rgba(59,130,246,0.13) 0%, rgba(59,130,246,0) 70%)",
            }}
          />
        </>
      ) : (
        <div
          className="absolute inset-x-0 -top-[70px] h-[140px]"
          style={{
            background: `linear-gradient(180deg, ${from}00 0%, ${from} 34%, ${to} 66%, ${to}00 100%)`,
          }}
        />
      )}
    </div>
  );
}
