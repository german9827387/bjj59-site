// In-memory rate limiter: max 20 requests per IP per minute
const chatRateLimit = new Map<string, { count: number; resetAt: number }>();
const CHAT_MAX_RPM = 20;
const CHAT_WINDOW_MS = 60 * 1000;

function checkChatRateLimit(ip: string): boolean {
  const now = Date.now();
  const rec = chatRateLimit.get(ip);
  if (!rec || now > rec.resetAt) {
    chatRateLimit.set(ip, { count: 1, resetAt: now + CHAT_WINDOW_MS });
    return true;
  }
  if (rec.count >= CHAT_MAX_RPM) return false;
  rec.count++;
  return true;
}

export async function POST(req: NextRequest) {
  const ip = req.headers.get("x-forwarded-for")?.split(",")[0]?.trim() ?? "unknown";
  if (!checkChatRateLimit(ip)) {
    return NextResponse.json({ error: "Слишком много запросов. Подождите немного." }, { status: 429 });
  }

  try {
    const body = await req.json();
    const messages = body.messages;

    if (!Array.isArray(messages) || messages.length === 0) {
      return NextResponse.json({ error: "Invalid request" }, { status: 400 });
    }

    const sanitized = messages
      .slice(-12)
      .map((m: { role: string; content: string }) => ({
        role: m.role === "user" ? "user" : "assistant",
        content: String(m.content).slice(0, 800),
      }));

    const groqBody = JSON.stringify({
      model: "meta-llama/llama-4-scout-17b-16e-instruct",
      messages: [{ role: "system", content: SYSTEM_PROMPT }, ...sanitized],
      max_tokens: 400,
      temperature: 0.65,
    });

    const groqHeaders = {
      "Content-Type": "application/json",
      Authorization: `Bearer ${process.env.GROQ_API_KEY}`,
    };

    // Бюджет времени: 3 попытки x 12с + паузы 1.5с и 3с ≈ 40с < maxDuration (55с).
    // Раньше 4 x 40с могли выйти за лимит, и функция падала по таймауту.
    let response!: Response;
    for (let attempt = 1; attempt <= 3; attempt++) {
      const controller = new AbortController();
      const timeout = setTimeout(() => controller.abort(), 12000);
      try {
        response = await fetch("https://api.groq.com/openai/v1/chat/completions", {
          method: "POST",
          headers: groqHeaders,
          body: groqBody,
          signal: controller.signal,
        });
      } finally {
        clearTimeout(timeout);
      }
      if (response.status !== 429) break;
      if (attempt === 3) break;
      const retryAfter = response.headers.get("retry-after");
      const waitMs = retryAfter ? Math.min(parseFloat(retryAfter) * 1000, 3000) : attempt * 1500;
      await new Promise((r) => setTimeout(r, waitMs));
    }

    if (!response.ok) {
      const errBody = await response.json().catch(() => ({}));
      console.error("[chat] Groq error", response.status, JSON.stringify(errBody));
      return NextResponse.json({ error: "AI unavailable" }, { status: 502 });
    }

    const data = await response.json();
    const raw: string = data.choices?.[0]?.message?.content ?? "";
    const leadMatch = raw.match(/\[ЛИДА\|([^|]*)\|([^|]*)\|([^|]*)\|([^\]]*)\]/);
    const sendLead = !!leadMatch;
    const leadName = leadMatch?.[1]?.trim() ?? "";
    const leadPhone = leadMatch?.[2]?.trim() ?? "";
    const leadDirection = leadMatch?.[3]?.trim() ?? "";
    const leadDayTime = leadMatch?.[4]?.trim() ?? "";
    let reply = raw.replace(/\[ЛИДА[^\]]*\]/, "").trim();
    if (!reply) reply = "Уточните, пожалуйста — не совсем понял ваш ответ 😊";
    return NextResponse.json({ reply, sendLead, leadName, leadPhone, leadDirection, leadDayTime });
  } catch {
    return NextResponse.json({ error: "Server error" }, { status: 500 });
  }
}
