/**
 * Факты об академии, которые считаются, а не пишутся руками.
 *
 * «Лет в Перми» жило четырьмя копиями: в настройках, в мета-описании, на
 * страницах направлений и в промпте чата — и уже разъехалось (14 против 13).
 * Теперь единственная константа — год открытия, а число лет выводится из
 * него и само растёт каждый январь.
 */
export const FOUNDED_YEAR = 2012;

export function yearsInPerm(now: Date = new Date()): number {
  return now.getFullYear() - FOUNDED_YEAR;
}
